export const t = strings.ar;

export function friendlyError(error: unknown): string {
  const message =
    error instanceof Error
      ? error.message.toLowerCase()
      : String(error ?? '').toLowerCase();

  if (message.includes('supabase_not_configured')) return t.errors.setup;
  if (
    message.includes('network') ||
    message.includes('fetch failed') ||
    message.includes('offline')
  ) {
    return t.errors.offline;
  }
  if (message.includes('invalid login credentials')) return t.auth.errors.invalid;
  if (message.includes('user already registered')) return t.auth.errors.exists;
  if (message.includes('email not confirmed')) return t.auth.errors.unconfirmed;
  if (message.includes('password should be at least')) return t.auth.errors.weak;
  return t.errors.generic;
}
